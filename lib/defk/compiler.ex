    len: "an array",
    div: "two i64 values",
    rem: "two i64 values",
    float: "a number",
    trunc: "a number",
    round: "a number",
    abs: "a number",
    min: "two numbers of the same type",
    max: "two numbers of the same type",
    pow: "two numbers",
    sqrt: "a number",
