defmodule Defk.Compiler do
  @moduledoc false
  # Typecheck defk kernels and lower them to one C translation unit.
  #
  # Every kernel body is lowered to C text over plain locals and emitted as a
  # resumable state machine called from Elixir. Locals live in registers; at a
  # safepoint that decides to yield they are spilled into a frame struct and
  # restored on resume. A call to another kernel is inlined (see "calls"), so
  # the callee's loops are the caller's loops and yield like them.
  #
  # Types:  :i64 | :f64 | :bool | {:arr, :f64 | :i64 | :u8} | {:tuple, [type]}

  @scalars [:i64, :f64, :bool]
  @elems [:f64, :i64, :u8]
  @math1 [:sqrt, :exp, :log, :sin, :cos]
  # range facts carried by values (see "range facts" below)
  @facts [:lo, :hi, :lb, :ub, :len_lo, :len_lb]

  # forms that never yield: safepoints vanish and resume dispatch is dead code
  @no_yield_macros "#define DEFK_SP(N, W)\n#define DEFK_SHORT(R) 1\n#define DEFK_TICKS(W)\n#define DEFK_RESUMING 0\nint defk_rs = 0;\n"
  @undef_macros "#undef DEFK_SP\n#undef DEFK_SHORT\n#undef DEFK_TICKS\n#undef DEFK_RESUMING\n"

  # ---------------------------------------------------------------- entry ---

  # opts: nif_name - the name each kernel's NIF is registered under
  def compile(module, raw_kernels, file, opts \\ []) do
    Process.put(:defk_file, file)
    kernels = raw_kernels |> Enum.with_index() |> Enum.map(&parse_kernel/1)

    sigs = Map.new(kernels, &{{&1.name, &1.arity}, &1})

    dups = kernels |> Enum.frequencies_by(&{&1.name, &1.arity}) |> Enum.filter(&(elem(&1, 1) > 1))
    for {{name, arity}, _} <- dups, do: err!([], "kernel #{name}/#{arity} defined more than once")

    lowered = Enum.map(kernels, &lower_kernel(&1, sigs))

    c =
      [
        "/* Generated by defk for #{inspect(module)} - do not edit */\n",
        "#include \"defk_runtime.h\"\n\n",
        Enum.map(lowered, &emit_entry/1),
        emit_init(module, lowered, Keyword.get(opts, :nif_name, & &1))
      ]
      |> IO.iodata_to_binary()

    {c, Enum.map(lowered, &Map.take(&1, [:name, :arity, :params, :ret]))}
  end

  # ------------------------------------------------------------ parsing ----

  defp parse_kernel({%{head: head, opts: opts, body: body, line: line}, idx}) do
    meta = [line: line]

    {call, ret_ast} =
      case head do
        {:"::", _, [call, ret]} -> {call, ret}
        _ -> err!(meta, "kernel head must be `name(arg :: type, ...) :: return_type`")
      end

    {name, params} =
      case call do
        {name, _, args} when is_atom(name) and is_list(args) -> {name, args}
        {name, _, ctx} when is_atom(name) and is_atom(ctx) -> {name, []}
        _ -> err!(meta, "bad kernel head #{Macro.to_string(head)}")
      end

    params =
      Enum.map(params, fn
        {:"::", m, [{p, _, ctx}, t]} when is_atom(p) and is_atom(ctx) ->
          ty = parse_type(t, m)
          if match?({:tuple, _}, ty), do: err!(m, "tuple parameters are not supported")
          {p, ty}

        other ->
          err!(meta, "parameter must be `name :: type`, got: #{Macro.to_string(other)}")
      end)

    for k <- Keyword.keys(opts), k != :yield, do: err!(meta, "unknown defk option #{inspect(k)}")
    body || err!(meta, "kernel #{name} has no body")

    %{
      name: name,
      arity: length(params),
      params: params,
      ret: parse_type(ret_ast, meta),
      body: body,
      yield: Keyword.get(opts, :yield, true),
      meta: meta,
      cid: "k#{idx}_#{sanitize(name)}"
    }
  end

  defp parse_type({t, _, ctx}, _) when t in @scalars and is_atom(ctx), do: t
  defp parse_type([{t, _, ctx}], _) when t in @elems and is_atom(ctx), do: {:arr, t}
  defp parse_type({a, b}, m), do: {:tuple, [parse_type(a, m), parse_type(b, m)]}
  defp parse_type({:{}, _, ts}, m), do: {:tuple, Enum.map(ts, &parse_type(&1, m))}

  defp parse_type(t, m),
    do: err!(m, "unknown type #{Macro.to_string(t)}; use i64, f64, bool, [f64], [i64], [u8] or tuples")

  # ------------------------------------------------------------ kernels ----

  defp lower_kernel(k, sigs) do
    Process.put(:defk_n, 0)
    Process.put(:defk_decls, [])
    Process.put(:defk_sp, 0)
    Process.put(:defk_sps, [])
    Process.put(:defk_loops, [])
    Process.put(:defk_nloops, 0)
    Process.put(:defk_nhalts, 0)
    Process.put(:defk_halts_emitted, 0)

    vars =
      Map.new(k.params, fn {p, t} ->
        c = "p_#{sanitize(p)}"
        {p, %{c: c, t: t, owned: false, var: c}}
      end)

    env = %{vars: vars, sigs: sigs, inlining: [{k.name, k.arity}]}
    {stmts, val} = lower_block(k.body, env)
    {ret_stmts, ret_vals} = coerce_return(val, k.ret, k.meta)

    Map.merge(k, %{
      stmts: [stmts, ret_stmts],
      ret_vals: ret_vals,
      decls: Enum.reverse(Process.get(:defk_decls)),
      sp_count: Process.get(:defk_sp),
      sps: Process.get(:defk_sps)
    })
  end

  defp coerce_return(%{t: {:tuple, ts}, elems: elems}, {:tuple, rts}, meta)
       when length(ts) == length(rts) do
    vals =
      Enum.zip_with(elems, rts, fn v, rt ->
        match?({:arr, _}, rt) and not v.owned &&
          err!(meta, "a returned array must be created with alloc/2 inside the kernel")

        coerce!(v, rt, meta, "return value").c
      end)

    {[], Enum.zip(vals, rts)}
  end

  defp coerce_return(%{t: {:arr, _} = t} = v, t, meta) do
    v.owned ||
      err!(meta, "a returned array must be created with alloc/2 inside the kernel (not supported yet)")

    {[], [{v.c, t}]}
  end

  defp coerce_return(v, rt, meta), do: {[], [{coerce!(v, rt, meta, "return value").c, rt}]}

  defp coerce!(%{t: t} = v, t, _meta, _what), do: v
  defp coerce!(%{t: :i64} = v, :f64, _meta, _what), do: %{v | c: to_f(v), t: :f64}

  defp coerce!(v, t, meta, what),
    do: err!(meta, "#{what} has type #{fmt(v.t)}, expected #{fmt(t)}")

  # ------------------------------------------------------------- blocks ----

  defp exprs({:__block__, m, []}), do: err!(m, "empty block")
  defp exprs({:__block__, _, es}), do: es
  defp exprs(e), do: [e]

  # A block whose last expression is its value.
  defp lower_block(ast, env), do: do_block(exprs(ast), env)

  defp do_block([{:=, _, [{{:., _, [Access, :get]}, _, _}, _]} = last], _env),
    do: err!(meta(last), "an array write has no value; it cannot be the last expression here")

  defp do_block([{:=, m, [lhs, rhs]}], env) do
    {s, v} = lower_expr(rhs, env)
    {s2, _} = bind(lhs, v, env, m)
    {[s, s2], v}
  end

  defp do_block([last], env), do: lower_expr(last, env)

  defp do_block([e | rest], env) do
    {s1, env} = lower_stmt(e, env)
    {s2, v} = do_block(rest, env)
    {[s1, s2], v}
  end

  # A block evaluated only for effect.
  defp lower_stmts(ast, env) do
    Enum.reduce(exprs(ast), {[], env}, fn e, {acc, env} ->
      {s, env} = lower_stmt(e, env)
      {[acc, s], env}
    end)
  end

  # --------------------------------------------------------- statements ----

  defp lower_stmt({:=, m, [{{:., _, [Access, :get]}, _, [arr, idx]}, rhs]}, env) do
    {sa, a} = lower_expr(arr, env)
    match?({:arr, _}, a.t) || err!(m, "cannot index into #{fmt(a.t)}")
    a.owned || err!(m, "only arrays created with alloc/2 are writable (inputs are read-only)")
    {si, i} = lower_expr(idx, env)
    i = coerce!(i, :i64, m, "array index")
    {sv, v} = lower_expr(rhs, env)
    {:arr, e} = a.t

    vc =
      case e do
        :f64 -> coerce!(v, :f64, m, "stored value").c
        :i64 -> coerce!(v, :i64, m, "stored value").c
        :u8 -> "defk_to_u8(ctx, #{coerce!(v, :i64, m, "stored value").c})"
      end

    store =
      if in_bounds?(a, i),
        do: "(#{a.c}).data[#{i.c}] = #{vc};\n",
        else: "defk_put_#{e}(ctx, #{a.c}, #{i.c}, #{vc});\n"

    {[sa, si, sv, store], env}
  end

  defp lower_stmt({:=, m, [lhs, rhs]}, env) do
    {s, v} = lower_expr(rhs, env)
    {s2, env} = bind(lhs, v, env, m)
    {[s, s2], env}
  end

  defp lower_stmt({:if, m, [cond, kw]}, env) when is_list(kw) do
    {sc, c} = lower_cond(cond, env, m)
    {sa, _} = lower_stmts(Keyword.fetch!(kw, :do), env)

    case Keyword.fetch(kw, :else) do
      {:ok, e} ->
        {sb, _} = lower_stmts(e, env)
        {[sc, "if (#{c}) {\n", sa, "} else {\n", sb, "}\n"], env}

      :error ->
        {[sc, "if (#{c}) {\n", sa, "}\n"], env}
    end
  end

  defp lower_stmt({:case, m, [subject, [do: clauses]]}, env) do
    {ss, arms, cenv} = case_arms(subject, clauses, m, env)
    {[ss, branch_chain(arms, cenv, m, &elem(lower_stmts(&1, &2), 0))], env}
  end

  defp lower_stmt({:for, m, args} = ast, env) do
    case parse_for(args, m) do
      {quals, nil, body} ->
        loops = lower_quals(quals, env, fn env -> elem(lower_stmts(body, env), 0) end)
        {loops, env}

      _reduce ->
        {s, v} = lower_expr(ast, env)
        {[s, discard(v)], env}
    end
  end

  defp lower_stmt(e, env) do
    {s, v} = lower_expr(e, env)
    {[s, discard(v)], env}
  end

  defp discard(%{elems: _}), do: []
  defp discard(%{c: c}), do: "(void)(#{c});\n"

  defp bind({name, m, ctx}, v, env, _) when is_atom(name) and is_atom(ctx) do
    cond do
      String.starts_with?(Atom.to_string(name), "_") ->
        {[], env}

      match?({:tuple, _}, v.t) ->
        err!(m, "bind tuples by destructuring: `{a, b} = ...`")

      # arrays are references: alias the binding instead of copying the view
      match?({:arr, _}, v.t) and v[:var] != nil ->
        {[], put_var(env, name, v)}

      true ->
        c = fresh(name, v.t)
        b = Map.merge(Map.take(v, @facts), %{c: c, t: v.t, owned: v[:owned] || false, var: c})
        {"#{c} = #{v.c};\n", put_var(env, name, b)}
    end
  end

  defp bind(pat, %{elems: elems}, env, m) when is_tuple(pat) do
    pats = tuple_items(pat) || err!(m, "cannot match #{Macro.to_string(pat)}")

    length(pats) == length(elems) ||
      err!(m, "tuple pattern has #{length(pats)} elements, value has #{length(elems)}")

    Enum.zip(pats, elems)
    |> Enum.reduce({[], env}, fn {p, e}, {acc, env} ->
      {s, env} = bind(p, e, env, m)
      {[acc, s], env}
    end)
  end

  defp bind(pat, _v, _env, m),
    do: err!(m, "only variables and tuples of variables can be matched, got: #{Macro.to_string(pat)}")

  defp put_var(env, name, v), do: %{env | vars: Map.put(env.vars, name, Map.put(v, :var, v.c))}

  defp tuple_items({a, b}), do: [a, b]
  defp tuple_items({:{}, _, items}), do: items
  defp tuple_items(_), do: nil

  # -------------------------------------------------------- expressions ----
  # lower_expr(ast, env) :: {c_statements, value}
  # value :: %{c: c_expr, t: type, owned: bool, var: cname | nil}
  #        | %{t: {:tuple, ts}, elems: [value]}

  defp lower_expr(n, _env) when is_integer(n) do
    n in -0x8000000000000000..0x7FFFFFFFFFFFFFFF || err!([], "integer literal #{n} does not fit in i64")
    {[], Map.merge(val("INT64_C(#{n})", :i64), %{lo: n, hi: n})}
  end

  defp lower_expr(f, _env) when is_float(f), do: {[], val(:erlang.float_to_binary(f, [:short]), :f64)}
  defp lower_expr(true, _env), do: {[], val("1", :bool)}
  defp lower_expr(false, _env), do: {[], val("0", :bool)}

  defp lower_expr({name, m, ctx}, env) when is_atom(name) and is_atom(ctx) do
    case env.vars do
      %{^name => v} -> {[], v}
      _ -> err!(m, "undefined variable #{name}")
    end
  end

  defp lower_expr({:__block__, _, _} = b, env), do: lower_block(b, env)

  defp lower_expr(tuple, env) when is_tuple(tuple) and tuple_size(tuple) == 2,
    do: lower_tuple(Tuple.to_list(tuple), env)

  defp lower_expr({:{}, _, items}, env), do: lower_tuple(items, env)

  defp lower_expr({{:., _, [Access, :get]}, m, [arr, idx]}, env) do
    {sa, a} = lower_expr(arr, env)
    match?({:arr, _}, a.t) || err!(m, "cannot index into #{fmt(a.t)}")
    {si, i} = lower_expr(idx, env)
    i = coerce!(i, :i64, m, "array index")
    {:arr, e} = a.t

    get =
      if in_bounds?(a, i),
        do: "(#{a.c}).data[#{i.c}]",
        else: "defk_get_#{e}(ctx, #{a.c}, #{i.c})"

    {[sa, si], if(e == :u8, do: u8_val("((int64_t)#{get})"), else: val(get, e))}
  end

  defp lower_expr({:if, m, [cond, kw]}, env) when is_list(kw) do
    else_ast = Keyword.get(kw, :else) || err!(m, "`if` used as a value needs an else branch")
    lower_arms([{cond, Keyword.fetch!(kw, :do)}, {true, else_ast}], "if", m, env)
  end

  defp lower_expr({:cond, m, [[do: clauses]]}, env) do
    {last_cond, _} = List.last(clauses) |> clause_parts()
    last_cond == true || err!(m, "`cond` used as a value must end with a `true ->` clause")
    lower_arms(Enum.map(clauses, &clause_parts/1), "cond", m, env)
  end

  defp lower_expr({:case, m, [subject, [do: clauses]]}, env) do
    {ss, arms, cenv} = case_arms(subject, clauses, m, env)
    {sa, v} = lower_arms(arms, "case", m, cenv)
    {[ss, sa], v}
  end

  defp lower_expr({:case, m, _}, _env), do: err!(m, "`case` needs a do block with `pattern -> body` clauses")

  defp lower_expr({{:., _, [{:__aliases__, _, [:Enum]}, :reduce_while]}, m, args}, env) do
    case args do
      [src, init, {:fn, _, [{:->, _, [[x, acc], body]}]}] -> lower_reduce_while(src, init, x, acc, body, env, m)
      _ -> err!(m, "usage: Enum.reduce_while(enumerable, acc, fn x, acc -> {:cont, acc} | {:halt, acc} end), with one fn clause and no guard")
    end
  end

  # Enum.all?/any? with a predicate fn are reduce_while with a bool accumulator
  defp lower_expr({{:., _, [{:__aliases__, _, [:Enum]}, f]}, m, args}, env) when f in [:all?, :any?] do
    {src, x, pred} =
      case args do
        [src, {:fn, _, [{:->, _, [[x], pred]}]}] -> {src, x, pred}
        _ -> err!(m, "usage: Enum.#{f}(enumerable, fn x -> boolean end), with one fn clause and no guard")
      end

    # all?: halt with false at the first false; any?: halt with true at the first true
    {init, kw} =
      if f == :all?,
        do: {true, [do: {:cont, true}, else: {:halt, false}]},
        else: {false, [do: {:halt, true}, else: {:cont, false}]}

    lower_reduce_while(src, init, x, {:_, m, nil}, {:if, m, [pred, kw]}, env, m)
  end

  defp lower_expr({:for, m, args}, env) do
    case parse_for(args, m) do
      {_quals, nil, _} -> err!(m, "`for` without `reduce:` has no value in a kernel")
      {quals, {:reduce, init}, clauses} -> lower_reduce(quals, init, clauses, env, m)
    end
  end

  defp lower_expr({op, m, [a, b]}, env) when op in [:+, :-, :*, :/] do
    {sa, va} = lower_expr(a, env)
    {sb, vb} = lower_expr(b, env)
    numeric!(va, m, op)
    numeric!(vb, m, op)

    v =
      case {op, va.t, vb.t} do
        {:/, _, _} -> val("defk_fdiv(ctx, #{to_f(va)}, #{to_f(vb)})", :f64)
        {:+, :i64, :i64} -> Map.merge(val("defk_add_i64#{checked(env)}, #{va.c}, #{vb.c})", :i64), add_facts(va, vb))
        {:-, :i64, :i64} -> Map.merge(val("defk_sub_i64#{checked(env)}, #{va.c}, #{vb.c})", :i64), sub_facts(va, vb))
        {:*, :i64, :i64} -> val("defk_mul_i64#{checked(env)}, #{va.c}, #{vb.c})", :i64)
        _ -> val("(#{to_f(va)} #{op} #{to_f(vb)})", :f64)
      end

    {[sa, sb], v}
  end

  defp lower_expr({op, m, [a, b]}, env) when op in [:==, :!=, :===, :!==, :<, :>, :<=, :>=] do
    {sa, va} = lower_expr(a, env)
    {sb, vb} = lower_expr(b, env)

    c =
      cond do
        va.t == :bool and vb.t == :bool and op in [:==, :!=, :===, :!==] ->
          "(#{va.c} #{cop(op)} #{vb.c})"

        op in [:===, :!==] and va.t != vb.t and numeric?(va) and numeric?(vb) ->
          if op == :===, do: "0", else: "1"

        numeric?(va) and numeric?(vb) and va.t == vb.t ->
          "(#{va.c} #{cop(op)} #{vb.c})"

        numeric?(va) and numeric?(vb) ->
          "(#{to_f(va)} #{cop(op)} #{to_f(vb)})"

        true ->
          err!(m, "cannot compare #{fmt(va.t)} #{op} #{fmt(vb.t)}")
      end

    {[sa, sb], val(c, :bool)}
  end

  defp lower_expr({op, m, [a, b]}, env) when op in [:and, :or, :&&, :||] do
    {sa, va} = lower_expr(a, env)
    {sb, vb} = lower_expr(b, env)
    bool!(va, m, op)
    bool!(vb, m, op)
    cop = if op in [:and, :&&], do: "&&", else: "||"

    if IO.iodata_length(sb) == 0 do
      {sa, val("(#{va.c} #{cop} #{vb.c})", :bool)}
    else
      # right side needs statements: keep short-circuit semantics explicitly
      tmp = fresh("sc", :bool)
      test = if cop == "&&", do: tmp, else: "!#{tmp}"
      {[sa, "#{tmp} = #{va.c};\nif (#{test}) {\n", sb, "#{tmp} = #{vb.c};\n}\n"], val(tmp, :bool, tmp)}
    end
  end

  defp lower_expr({op, m, [a]}, env) when op in [:not, :!] do
    {s, v} = lower_expr(a, env)
    bool!(v, m, op)
    {s, val("(!#{v.c})", :bool)}
  end

  defp lower_expr({:-, m, [a]}, env) do
    {s, v} = lower_expr(a, env)
    numeric!(v, m, :-)
    c = if v.t == :i64, do: "defk_neg_i64#{checked(env)}, #{v.c})", else: "(-#{v.c})"
    {s, val(c, v.t)}
  end

  defp lower_expr({:+, m, [a]}, env) do
    {s, v} = lower_expr(a, env)
    numeric!(v, m, :+)
    {s, v}
  end

  # dbg/IO.inspect are for Elixir mode (Defk.ElixirMode); native code ignores them
  defp lower_expr({:dbg, _, [x | _]}, env), do: lower_expr(x, env)
  defp lower_expr({{:., _, [{:__aliases__, _, [:IO]}, :inspect]}, _, [x | _]}, env), do: lower_expr(x, env)

  # :math.sqrt(x) etc. map onto the builtins
  defp lower_expr({{:., _, [:math, fun]}, m, args}, env) when fun in [:pow | @math1],
    do: lower_call(fun, args, m, env)

  defp lower_expr({name, m, args}, env) when is_atom(name) and is_list(args),
    do: lower_call(name, args, m, env)

  defp lower_expr(other, _env),
    do: err!(meta(other), "unsupported expression in kernel: #{Macro.to_string(other)}")

  defp lower_tuple(items, env) do
    {stmts, elems} =
      Enum.map_reduce(items, [], fn item, acc ->
        {s, v} = lower_expr(item, env)
        match?(%{elems: _}, v) && err!(meta(item), "nested tuples are not supported")
        {s, [v | acc]}
      end)

    elems = Enum.reverse(elems)
    {stmts, %{t: {:tuple, Enum.map(elems, & &1.t)}, elems: elems}}
  end

  defp lower_cond(cond, env, m) do
    {s, v} = lower_expr(cond, env)
    bool!(v, m, :if)
    {s, v.c}
  end

  defp clause_parts({:->, _, [[c], body]}), do: {c, body}

  defp branch_type!(vals, m) do
    case Enum.uniq_by(vals, & &1.t) do
      [%{t: {:tuple, _}} | _] -> err!(m, "branches returning tuples are not supported")
      [%{t: {:arr, _}} | _] -> err!(m, "branches returning arrays are not supported")
      [%{t: t}] -> t
      many -> err!(m, "branches have different types: #{Enum.map_join(many, ", ", &fmt(&1.t))}")
    end
  end

  # The clauses of an `if` or `cond` value, the last one `true ->`. Each arm is
  # {cond_ast, body_ast, {stmts, c} | :else, body_stmts, body_val}.
  # A `case` without a catch-all ends in {:nomatch, stmts} instead, which
  # raises CaseClauseError.
  defp lower_arms(clauses, name, m, env) do
    arms =
      Enum.map(clauses, fn
        {:nomatch, s} ->
          {nil, nil, :nomatch, s, nil}

        {c, body} ->
          cond = if c == true, do: :else, else: lower_cond(c, env, m)
          {sb, v} = lower_block(body, env)
          {c, body, cond, sb, v}
      end)

    t = branch_type!(for({_, _, _, _, v} <- arms, v, do: v), m)
    tmp = fresh(name, t)
    code = if select?(arms), do: select(arms, t, tmp, m, env), else: chain(arms, tmp)
    {code, val(tmp, t, tmp)}
  end

  # An `if` or `cond` value whose arms (and conditions after the first) are pure
  # arithmetic is compiled as a select: every arm is computed with overflow
  # flags instead of raising, and only an overflow replays the clauses with the
  # raising checks. A raise inside one arm would otherwise keep clang from
  # if-converting the branch; it then threads the branch into the loop that
  # computed the condition, which made `if prime?(i), do: count + 1, else:
  # count` 1.7x slower than C (defk-jp3). The first condition always runs, so
  # it is evaluated once as written and may call kernels.
  # (A `case` with no catch-all ends in a :nomatch arm and is never a select.)
  defp select?([{_, _, {_, _}, _, _} | later] = arms) do
    case Enum.split(later, -1) do
      {later, [{_, _, :else, _, _}]} ->
        Enum.all?(arms, fn {_, body, _, sb, _} -> IO.iodata_length(sb) == 0 and speculate?(body) end) and
          Enum.all?(later, fn
            {c, _, {sc, _}, _, _} -> IO.iodata_length(sc) == 0 and speculate?(c)
            _ -> false
          end)

      _ ->
        false
    end
  end

  defp select?(_arms), do: false

  defp select([{_, _, {sc, c}, _, _} | later] = arms, t, tmp, m, env) do
    later = Enum.drop(later, -1)

    flagged = fn flag ->
      fenv = Map.put(env, :ovf, flag)
      conds = for {ca, _, _, _, _} <- later, do: elem(lower_cond(ca, fenv, m), 1)
      {conds, for({_, body, _, _, _} <- arms, do: elem(lower_block(body, fenv), 1).c)}
    end

    plain_conds = for {_, _, {_, cc}, _, _} <- later, do: cc
    plain_bodies = for {_, _, _, _, v} <- arms, do: v.c

    if flagged.("_") == {plain_conds, plain_bodies} do
      # nothing can raise: clang if-converts the plain branches itself
      chain(arms, tmp)
    else
      ovf = fresh("ovf", :bool)
      {fconds, fbodies} = flagged.(ovf)
      [cv | cvs] = for _ <- [c | fconds], do: fresh("cond", :bool)
      tvs = for _ <- arms, do: fresh("arm", t)

      [
        sc,
        "#{cv} = #{c};\n#{ovf} = 0;\n",
        Enum.zip_with(cvs, fconds, &"#{&1} = #{&2};\n"),
        Enum.zip_with(tvs, fbodies, &"#{&1} = #{&2};\n"),
        "#{tmp} = ",
        Enum.zip_with([cv | cvs], tvs, &"#{&1} ? #{&2} : "),
        "#{List.last(tvs)};\n",
        "if (DEFK_UNLIKELY(#{ovf})) {\n",
        Enum.zip_with([cv | plain_conds], plain_bodies, &"if (#{&1}) (void)(#{&2});\nelse "),
        "(void)(#{List.last(plain_bodies)});\n}\n"
      ]
    end
  end

  defp chain(arms, tmp) do
    List.foldr(arms, [], fn
      {_, _, :else, sb, v}, _rest -> [sb, "#{tmp} = #{v.c};\n"]
      {_, _, :nomatch, s, _}, _rest -> s
      {_, _, {sc, c}, sb, v}, rest -> [sc, "if (#{c}) {\n", sb, "#{tmp} = #{v.c};\n} else {\n", rest, "}\n"]
    end)
  end

  defp checked(%{ovf: flag}), do: "_s(&#{flag}"
  defp checked(_env), do: "(ctx"

  # pure expressions that can only fail by i64 overflow: safe to evaluate untaken
  defp speculate?({:__block__, _, [e]}), do: speculate?(e)
  defp speculate?(x) when is_number(x) or is_boolean(x), do: true
  defp speculate?({name, _, ctx}) when is_atom(name) and is_atom(ctx), do: true

  defp speculate?({op, _, args}) when op in [:+, :-, :*, :==, :!=, :===, :!==, :<, :>, :<=, :>=, :and, :or, :&&, :||, :not, :!],
    do: Enum.all?(args, &speculate?/1)

  defp speculate?(_), do: false

  # ---------------------------------------------------------------- calls --

  defp lower_call(:alloc, [{e, _, ctx}, n], m, env) when e in @elems and is_atom(ctx) do
    {s, v} = lower_expr(n, env)
    v = coerce!(v, :i64, m, "alloc/2 length")
    arr = %{c: "defk_alloc_#{e}(ctx, #{v.c})", t: {:arr, e}, owned: true, var: nil}
    {s, Map.merge(arr, %{len_lo: v[:lo], len_lb: lb(v)})}
  end

  defp lower_call(:alloc, _, m, _), do: err!(m, "usage: alloc(f64 | i64 | u8, length)")

  defp lower_call(name, args, m, env) do
    {stmts, vals} = Enum.map_reduce(args, [], fn a, acc ->
      {s, v} = lower_expr(a, env)
      {s, [v | acc]}
    end)

    vals = Enum.reverse(vals)
    Enum.each(vals, &(match?(%{elems: _}, &1) && err!(m, "tuples cannot be passed as arguments")))

    # a builtin is an expression; an inlined kernel call also has statements
    case builtin(name, vals, m, env) do
      {s, v} -> {[stmts, s], v}
      v -> {stmts, v}
    end
  end

  defp builtin(:len, [%{t: {:arr, _}} = a], _m, _) do
    # a view that is not a variable (e.g. a kernel call) is a new array each time it is evaluated
    own = if a.var, do: %{a.c => 0}, else: %{}
    facts = %{lo: max(a[:len_lo] || 0, 0), lb: Map.merge(len_lb(a), own), ub: own}
    Map.merge(val("(#{a.c}).len", :i64), facts)
  end

  defp builtin(f, [%{t: :i64} = a, %{t: :i64} = b], _, _) when f in [:div, :rem],
    do: val("defk_#{f}_i64(ctx, #{a.c}, #{b.c})", :i64)
  defp builtin(:float, [a], m, _), do: (numeric!(a, m, :float); val(to_f(a), :f64))
  defp builtin(:trunc, [%{t: :i64} = a], _, _), do: a
  defp builtin(:trunc, [%{t: :f64} = a], _, _), do: val("defk_trunc(ctx, #{a.c})", :i64)
  defp builtin(:round, [%{t: :i64} = a], _, _), do: a
  defp builtin(:round, [%{t: :f64} = a], _, _), do: val("defk_round(ctx, #{a.c})", :i64)
  defp builtin(:abs, [%{t: :i64} = a], _, _), do: val("defk_abs_i64(ctx, #{a.c})", :i64)
  defp builtin(:abs, [%{t: :f64} = a], _, _), do: val("fabs(#{a.c})", :f64)

  defp builtin(f, [%{t: :i64} = a, %{t: :i64} = b], _, _) when f in [:min, :max],
    do: Map.merge(val("defk_#{f}_i64(#{a.c}, #{b.c})", :i64), minmax_facts(f, a, b))

  defp builtin(f, [%{t: :f64} = a, %{t: :f64} = b], _, _) when f in [:min, :max],
    do: val("defk_#{f}_f64(#{a.c}, #{b.c})", :f64)

  defp builtin(f, [a], m, _) when f in @math1 do
    numeric!(a, m, f)
    c = if f in [:sqrt, :log], do: "defk_#{f}(ctx, #{to_f(a)})", else: "#{f}(#{to_f(a)})"
    val(c, :f64)
  end

  defp builtin(:pow, [a, b], m, _) do
    numeric!(a, m, :pow)
    numeric!(b, m, :pow)
    val("pow(#{to_f(a)}, #{to_f(b)})", :f64)
  end

  defp builtin(name, vals, m, env) do
    arity = length(vals)

    case Map.get(env.sigs, {name, arity}) do
      %{} = k ->
        match?({:tuple, _}, k.ret) &&
          err!(m, "kernel #{name}/#{arity} returns a tuple and can only be called from Elixir")

        inline(k, vals, m, env)

      nil ->
        sig = Enum.map_join(vals, ", ", &fmt(&1.t))
        err!(m, "unknown function #{name}(#{sig}); kernels can only call builtins and other defk kernels in this module")
    end
  end

  # A call to another kernel is lowered as the callee's body, inlined into the
  # caller with the arguments bound to its parameters. Its loops nest in the
  # caller's loops, so their safepoints spill and resume with the caller's
  # frame, and a long loop in a callee (several calls deep) yields like one in
  # the caller. A separately compiled callee would need its own frame and a
  # resume path into the middle of the caller's loop body (defk-jaj). The
  # arguments keep their range facts, so the callee may drop bounds checks a
  # standalone kernel needs. Code size grows with the number of call sites
  # along each call chain; recursion is rejected, so inlining terminates.
  defp inline(k, vals, m, env) do
    key = {k.name, k.arity}

    key in env.inlining &&
      err!(k.meta, "kernel #{k.name}/#{k.arity} is recursive; recursion is not allowed (kernel calls are inlined)")

    # bind each argument to a parameter once; array views are aliased like `b = a`
    {binds, vars} =
      Enum.zip_with(vals, k.params, fn v, {p, t} ->
        v = coerce!(v, t, m, "argument #{p} of #{k.name}")

        if match?({:arr, _}, t) and v.var != nil do
          {[], {p, %{v | owned: false}}}
        else
          c = fresh(p, t)
          {"#{c} = #{v.c};\n", {p, Map.merge(Map.take(v, @facts), %{c: c, t: t, owned: false, var: c})}}
        end
      end)
      |> Enum.unzip()

    cenv = %{vars: Map.new(vars), sigs: env.sigs, inlining: [key | env.inlining]}
    {sb, v} = lower_block(k.body, cenv)
    {[], [{c, t}]} = coerce_return(v, k.ret, k.meta)

    # a temporary, so the result is computed here and not where it is used
    tmp = fresh("#{k.name}_ret", t)
    {[binds, sb, "#{tmp} = #{c};\n"], %{val(tmp, t, tmp) | owned: true}}
  end

  # ---------------------------------------------------------------- loops --

  defp parse_for(args, m) do
    {kws, quals} = Enum.split_with(args, &(is_list(&1) and Keyword.keyword?(&1)))
    opts = Enum.concat(kws)

    for k <- Keyword.keys(opts), k not in [:do, :reduce],
        do: err!(m, "`for` option #{inspect(k)} is not supported in kernels")

    match?([{:<-, _, _} | _], quals) || err!(m, "`for` must start with a generator")
    body = Keyword.get(opts, :do) || err!(m, "`for` needs a do block")

    case Keyword.fetch(opts, :reduce) do
      {:ok, init} -> {quals, {:reduce, init}, body}
      :error -> {quals, nil, body}
    end
  end

  # Nest generators/filters; `inner.(env)` emits the innermost body.
  defp lower_quals([], env, inner), do: inner.(env)

  defp lower_quals([{:<-, m, [pat, src]} | rest], env, inner) do
    name =
      case pat do
        {n, _, ctx} when is_atom(n) and is_atom(ctx) -> n
        _ -> err!(m, "generator pattern must be a variable")
      end

    case src do
      {:.., _, [a, b]} -> range_loop(name, a, b, :auto, rest, env, inner, m)
      {:..//, _, [a, b, s]} -> range_loop(name, a, b, s, rest, env, inner, m)
      _ -> array_loop(name, src, rest, env, inner, m)
    end
  end

  defp lower_quals([filter | rest], env, inner) do
    {sc, c} = lower_cond(filter, env, meta(filter))
    [sc, "if (#{c}) {\n", lower_quals(rest, env, inner), "}\n"]
  end

  defp range_loop(name, a, b, step, rest, env, inner, m) do
    {sa, va} = lower_expr(a, env)
    {sb, vb} = lower_expr(b, env)
    va = coerce!(va, :i64, m, "range start")
    vb = coerce!(vb, :i64, m, "range end")
    i = fresh(name, :i64)
    e = fresh("stop", :i64)
    setup = [sa, sb, "#{i} = #{va.c};\n#{e} = #{vb.c};\n"]

    {setup, done, incr, iv, strip} =
      case literal_int(step) do
        k when is_integer(k) and k > 0 ->
          # counting up from a to b: in the body a <= i <= b
          facts = %{lo: va[:lo], hi: vb[:hi], lb: lb(va), ub: ub(vb)}
          iv = Map.merge(val(i, :i64), facts)
          strip = %{done_at: &"#{i} > #{&1}", remaining: "((uint64_t)#{e} - (uint64_t)#{i}) / #{k}", step: k}
          {[setup, range_limit(i, e, k, vb)], "#{i} > #{e}", "#{i} += #{k};\n", iv, strip}

        k when is_integer(k) and k < 0 ->
          strip = %{done_at: &"#{i} < #{&1}", remaining: "((uint64_t)#{i} - (uint64_t)#{e}) / #{-k}", step: k}
          {[setup, range_limit(i, e, k, vb)], "#{i} < #{e}", "#{i} -= #{-k};\n", val(i, :i64), strip}

        0 ->
          err!(m, "range step cannot be zero")

        nil ->
          st = fresh("step", :i64)

          step_setup =
            if step == :auto do
              # Elixir semantics: a..b counts down when a > b (use a..b//1 for "maybe empty")
              "#{st} = (#{i} <= #{e}) ? 1 : -1;\n"
            else
              {ss, vs} = lower_expr(step, env)
              vs = coerce!(vs, :i64, m, "range step")
              [ss, "#{st} = #{vs.c};\n",
               "if (#{st} == 0) defk_fail(ctx, DEFK_E_ARG, \"range step cannot be zero\");\n"]
            end

          {[setup, step_setup, range_limit(i, e, st, vb)], "(#{st} > 0 ? #{i} > #{e} : #{i} < #{e})", "#{i} += #{st};\n", val(i, :i64), nil}
      end

    env = put_var(env, name, iv)

    in_loop(fn id ->
      {body, flat?} = lower_quals_tracked(rest, env, inner)
      strip = strip && Map.merge(strip, %{var: i, stop: e})
      [setup, loop(id, done, strip, flat?, [body, incr])]
    end)
  end

  # Stepping past the last element of a range that ends within one step of the
  # i64 limit would overflow i (C UB: in practice i wraps, the exit test never
  # passes, the loop hangs without a safepoint, and an index proven in range
  # from i is not). Such a range raises before the loop starts (a limit, even
  # when a reduce_while halt would end it earlier). The test, one compare,
  # is dropped when the facts on the end prove it far enough from the limit,
  # e.g. an end <= len(a) + d with d <= 0: arrays are shorter than 2^61
  # elements (DEFK_ALLOC_MAX_BYTES, and the largest binary).
  @i64_min -0x8000000000000000
  @i64_max 0x7FFFFFFFFFFFFFFF
  defp range_limit(i, e, k, vb) do
    near_limit =
      cond do
        is_integer(k) and k > 0 ->
          safe? = (is_integer(vb[:hi]) and vb[:hi] <= @i64_max - k) or
                    (k <= @i64_max - 2 ** 61 and Enum.any?(ub(vb), fn {_, d} -> d <= 0 end))

          if !safe?, do: "#{e} > INT64_C(#{@i64_max - k})"

        is_integer(k) ->
          safe? = (is_integer(vb[:lo]) and vb[:lo] >= @i64_min - k) or
                    Enum.any?(lb(vb), fn {_, d} -> d >= @i64_min - k end)

          if !safe?, do: "#{e} < INT64_C(#{@i64_min - k})"

        true ->
          "(#{k} > 0 ? #{e} > INT64_MAX - #{k} : #{e} < INT64_MIN - #{k})"
      end

    if near_limit,
      do: "if (DEFK_UNLIKELY(#{near_limit})) defk_range_limit(ctx, #{i}, #{e}, #{k});\n",
      else: []
  end

  defp array_loop(name, src, rest, env, inner, m) do
    {s, a} = lower_expr(src, env)
    match?({:arr, _}, a.t) || err!(m, "cannot iterate over #{fmt(a.t)}")
    {:arr, e} = a.t

    # reference the view by variable so it is re-bound after a resume
    {s, arr} =
      if a[:var] do
        {s, a.c}
      else
        tmp = fresh("arr", a.t)
        {[s, "#{tmp} = #{a.c};\n"], tmp}
      end

    k = fresh("k", :i64)
    xt = if e == :u8, do: :i64, else: e
    x = fresh(name, xt)
    env = put_var(env, name, if(e == :u8, do: u8_val(x), else: val(x, xt)))

    # index is in range by construction: no bounds check
    in_loop(fn id ->
      {body, flat?} = lower_quals_tracked(rest, env, inner)
      body = ["#{x} = #{arr}.data[#{k}];\n", body, "#{k} += 1;\n"]
      strip = %{done_at: &"#{k} > #{&1}", remaining: "(uint64_t)(#{arr}.len - #{k} - 1)", step: 1, var: k, stop: "#{arr}.len - 1"}
      [s, "#{k} = 0;\n", loop(id, "#{k} >= #{arr}.len", strip, flat?, body)]
    end)
  end

  # Lower the rest of a loop and note whether that body is flat: no nested
  # loop, including one in an inlined kernel call, so one iteration costs a
  # bounded amount of work. flat :: false | :plain | :exits (a reduce_while
  # halt jumps out of it).
  defp lower_quals_tracked(rest, env, inner) do
    before = {Process.get(:defk_sp), Process.get(:defk_halts_emitted, 0)}
    body = lower_quals(rest, env, inner)

    flat =
      case {before, {Process.get(:defk_sp), Process.get(:defk_halts_emitted, 0)}} do
        {{sp, h}, {sp, h}} -> :plain
        {{sp, _}, {sp, _}} -> :exits
        _ -> false
      end

    {body, flat}
  end

  # A loop with a safepoint on every back-edge, except for a flat loop whose
  # trip count is known on entry:
  #   * short (< DEFK_STRIP trips left): the plain loop with no safepoint; its
  #     trips are charged to the budget afterwards and the enclosing loop's
  #     safepoint does the check, so at most DEFK_STRIP flat iterations per
  #     enclosing iteration go unchecked. A loop a reduce_while halt can leave
  #     (flat == :exits) charges them on entry instead, so the jump past the
  #     loop cannot skip the charge (it overcharges by under DEFK_STRIP).
  #   * long: strips of DEFK_STRIP iterations, one safepoint per strip
  # Neither inner loop has a safepoint, so clang can vectorise it. Forms that
  # never yield define DEFK_SHORT as 1 and the strip version is dead code.
  #   strip.remaining - trips left after the next one, as uint64
  #   strip.done_at   - the loop's exit test against a given last index
  defp loop(id, done, strip, flat, body) when is_map(strip) and flat in [:plain, :exits] do
    r = fresh("rem", {:c, "uint64_t"})
    se = fresh("strip_stop", :i64)
    %{var: i, stop: e, step: k} = strip

    # no overflow: taken only when the strip ends before the loop's last index
    strip_stop = "(int64_t)((uint64_t)#{i} + (uint64_t)(DEFK_STRIP - 1) * (uint64_t)INT64_C(#{k}))"

    ["#{r} = #{strip.remaining};\nif (DEFK_SHORT(#{r})) {\n",
     if(flat == :exits, do: "DEFK_TICKS(#{r} + 1)\n", else: []),
     "while (!(#{done})) {\n", body, "}\n",
     if(flat == :exits, do: [], else: "DEFK_TICKS(#{r} + 1)\n"),
     "} else {\n",
     "defk_l#{id}:;\nwhile (!(#{done})) {\n#{se} = #{strip.remaining} < DEFK_STRIP ? #{e} : #{strip_stop};\n",
     "while (!(#{strip.done_at.(se)})) {\n", body, "}\n", safepoint("DEFK_STRIP"), "}\n}\n"]
  end

  defp loop(id, done, _strip, _flat?, body),
    do: ["defk_l#{id}:;\nwhile (!(#{done})) {\n", resume_dispatch(), body, safepoint(), "}\n"]

  # Resuming re-enters loops only through their headers, so every loop keeps a
  # single entry (an irreducible CFG would cost LLVM most loop optimisations).
  # A safepoint is the last statement of its loop's body, so continuing after
  # it means re-testing that loop's condition. The kernel's top dispatch jumps
  # to the label in front of the outermost loop on the way to the safepoint;
  # the top of that loop's body dispatches to the next loop down, and so on.
  # The step that reaches the safepoint's own loop clears defk_rs.
  defp in_loop(fun) do
    id = Process.get(:defk_nloops) + 1
    Process.put(:defk_nloops, id)
    stack = Process.get(:defk_loops)
    Process.put(:defk_loops, [id | stack])
    res = fun.(id)
    Process.put(:defk_loops, stack)
    res
  end

  # Dispatch for the loops entered from here (the current loop body, or the
  # kernel top level when no loop is open).
  defp resume_dispatch do
    case resume_cases(Process.get(:defk_sps), Enum.reverse(Process.get(:defk_loops))) do
      [] -> []
      cases -> ["if (DEFK_RESUMING) switch (defk_rs) {\n", cases, "}\n"]
    end
  end

  # `here` is the path of loop ids (outermost first) whose body we are in
  defp resume_cases(sps, here) do
    depth = length(here)

    for {n, path} <- Enum.sort(sps), length(path) > depth, List.starts_with?(path, here) do
      # reaching the safepoint's own loop completes the resume (defk_lost_resume)
      clear = if length(path) == depth + 1, do: "defk_rs = F->resume = 0; ", else: ""
      "case #{n}: #{clear}goto defk_l#{Enum.at(path, depth)};\n"
    end
  end

  defp lower_reduce(quals, init_ast, clauses, env, m) do
    {pat, body} =
      case clauses do
        [{:->, _, [[pat], body]}] -> {pat, body}
        _ -> err!(m, "`for ..., reduce:` needs exactly one `acc -> body` clause")
      end

    {si, accs} = reduce_accs(pat, init_ast, "reduce: init", env, m)

    inner = fn genv ->
      {sb, res} = lower_block(body, acc_env(accs, genv))
      [sb, assign_accs(accs, res, m, "reduce body")]
    end

    {[si, lower_quals(quals, env, inner)], acc_result(accs)}
  end

  # Enum.reduce_while(src, init, fn x, acc -> ... end) is the loop of
  # `for x <- src`, with the accumulator of `for ..., reduce: init`. Every tail
  # position of the fn body is a literal {:cont, acc} or {:halt, acc} (see
  # lower_tail), so the next accumulator is assigned where the tuple is
  # written, and a halt jumps to a label after this loop. That leaves only
  # this loop (and the loops nested in it), so a halt in a nested
  # reduce_while ends the inner fold only, as in Elixir. Jumping out of loops
  # keeps every loop's single entry, which resume relies on (defk-nua).
  # `for ..., reduce:` with {:cont, acc}/{:halt, acc} is not early exit in
  # Elixir (the tuple becomes the next accumulator), so it is not one here.
  defp lower_reduce_while(src, init_ast, x, acc_pat, body, env, m) do
    {si, accs} = reduce_accs(acc_pat, init_ast, "Enum.reduce_while initial accumulator", env, m)
    id = Process.get(:defk_nhalts) + 1
    Process.put(:defk_nhalts, id)
    label = "defk_halt#{id}"

    leaf = fn tag, v_ast, env ->
      {s, v} = lower_expr(v_ast, env)
      assign = assign_accs(accs, v, m, "Enum.reduce_while {:#{tag}, acc}")
      if tag == :halt do
        Process.put({:defk_halted, id}, true)
        Process.put(:defk_halts_emitted, Process.get(:defk_halts_emitted, 0) + 1)
      end
      [s, assign, if(tag == :halt, do: "goto #{label};\n", else: [])]
    end

    inner = fn genv -> lower_tail(body, acc_env(accs, genv), leaf) end
    loops = lower_quals([{:<-, m, [x, src]}], env, inner)
    halt = if Process.delete({:defk_halted, id}), do: "#{label}:;\n", else: []
    {[si, loops, halt], acc_result(accs)}
  end

  # accumulators [{name, cvar, init_value}] from `acc` or `{a, b, ...}` and init
  defp reduce_accs(pat, init_ast, what, env, m) do
    {si, init} = lower_expr(init_ast, env)
    inits = Map.get(init, :elems, [init])
    pats = if is_tuple(pat) and tuple_items(pat), do: tuple_items(pat), else: [pat]

    length(pats) == length(inits) ||
      err!(m, "accumulator pattern has #{length(pats)} elements, #{what} has #{length(inits)}")

    accs =
      Enum.zip_with(pats, inits, fn p, v ->
        match?({:arr, _}, v.t) && err!(m, "array accumulators are not supported")

        name =
          case p do
            {n, _, ctx} when is_atom(n) and is_atom(ctx) -> n
            _ -> err!(m, "accumulator pattern must be a variable or tuple of variables")
          end

        {name, fresh(name, v.t), v}
      end)

    {[si, Enum.map(accs, fn {_, c, v} -> "#{c} = #{v.c};\n" end)], accs}
  end

  defp acc_env(accs, env) do
    Enum.reduce(accs, env, fn {name, c, v}, e ->
      if String.starts_with?(Atom.to_string(name), "_"), do: e, else: put_var(e, name, val(c, v.t))
    end)
  end

  defp assign_accs(accs, res, m, what) do
    results = Map.get(res, :elems, [res])

    length(results) == length(accs) ||
      err!(m, "#{what} has #{length(results)} values, accumulator has #{length(accs)}")

    outs =
      Enum.zip_with(accs, results, fn {name, _c, v}, r ->
        coerce!(r, v.t, m, "#{what} result for #{name}")
      end)

    case accs do
      [{_, c, _}] ->
        "#{c} = #{hd(outs).c};\n"

      _ ->
        # compute all new values before assigning (they may read each other)
        tmps = Enum.map(accs, fn {name, _, v} -> fresh("#{name}_next", v.t) end)

        [Enum.zip_with(tmps, outs, &"#{&1} = #{&2.c};\n"),
         Enum.zip_with(accs, tmps, fn {_, c, _}, t -> "#{c} = #{t};\n" end)]
    end
  end

  defp acc_result([{_, c, v}]), do: val(c, v.t, c)

  defp acc_result(accs),
    do: %{t: {:tuple, Enum.map(accs, &elem(&1, 2).t)}, elems: Enum.map(accs, fn {_, c, v} -> val(c, v.t, c) end)}

  # The body of a reduce_while fn: statements, then a tail that is a literal
  # {:cont, acc} or {:halt, acc}, or an if/cond/case whose branches end in one.
  # `leaf.(tag, acc_ast, env)` emits a tail tuple.
  defp lower_tail(ast, env, leaf) do
    {init, [last]} = Enum.split(exprs(ast), -1)

    {s, env} =
      Enum.reduce(init, {[], env}, fn e, {acc, env} ->
        {s, env} = lower_stmt(e, env)
        {[acc, s], env}
      end)

    [s, tail_expr(last, env, leaf)]
  end

  defp tail_expr({tag, v}, env, leaf) when tag in [:cont, :halt], do: leaf.(tag, v, env)
  defp tail_expr({:__block__, _, _} = b, env, leaf), do: lower_tail(b, env, leaf)

  defp tail_expr({:if, m, [c, kw]}, env, leaf) when is_list(kw) do
    else_ast = Keyword.get(kw, :else) || err!(m, "an `if` that ends a reduce_while fn needs an else branch returning {:cont, acc} or {:halt, acc}")
    branch_chain([{c, Keyword.fetch!(kw, :do)}, {true, else_ast}], env, m, &lower_tail(&1, &2, leaf))
  end

  defp tail_expr({:cond, m, [[do: clauses]]}, env, leaf) do
    arms = Enum.map(clauses, &clause_parts/1)
    match?({true, _}, List.last(arms)) || err!(m, "`cond` used as a value must end with a `true ->` clause")
    branch_chain(arms, env, m, &lower_tail(&1, &2, leaf))
  end

  defp tail_expr({:case, m, [subject, [do: clauses]]}, env, leaf) do
    {ss, arms, cenv} = case_arms(subject, clauses, m, env)
    [ss, branch_chain(arms, cenv, m, &lower_tail(&1, &2, leaf))]
  end

  defp tail_expr(other, _env, _leaf) do
    err!(meta(other), "a reduce_while fn must return a literal {:cont, acc} or {:halt, acc} in every branch, got: #{Macro.to_string(other)}")
  end

  # An if/else chain over [{cond_ast | true, body_ast} | {:nomatch, stmts}],
  # each body lowered by `lower_body.(body_ast, env)`.
  defp branch_chain(arms, env, m, lower_body) do
    arms
    |> Enum.map(fn
      {:nomatch, s} -> {:nomatch, s}
      {true, body} -> {true, lower_body.(body, env)}
      {c, body} -> {lower_cond(c, env, m), lower_body.(body, env)}
    end)
    |> List.foldr([], fn
      {:nomatch, s}, _ -> s
      {true, sb}, _ -> sb
      {{sc, c}, sb}, rest -> [sc, "if (#{c}) {\n", sb, "} else {\n", rest, "}\n"]
    end)
  end

  # ----------------------------------------------------------------- case --
  # `case` on an i64 or bool. Patterns: integer literals (bool: true/false),
  # `^pinned`, `_`, or a variable that binds the subject; each with an
  # optional guard. Lowered to [{cond_ast | true, body_ast}] for lower_arms
  # (a value; pure-arithmetic arms become a select) or branch_chain (a
  # statement or a reduce_while tail). The clauses test in order, like an
  # if/else chain; clang turns literal tests into a switch where that pays.
  # Like Elixir, a value no clause matches raises CaseClauseError, so a
  # catch-all is not required. Clauses after one that always matches are
  # unreachable and dropped. Returns {stmts, arms, env with the subject bound}.
  defp case_arms(subject, clauses, m, env) do
    {ss, sv} = lower_expr(subject, env)
    sv.t in [:i64, :bool] || err!(m, "`case` subject must be i64 or bool, got #{fmt(sv.t)}")

    c = fresh("case", sv.t)
    # a name no Elixir variable can have, bound to the subject evaluated once
    name = :"defk case #{c}"
    env = put_var(env, name, Map.merge(Map.take(sv, @facts), %{c: c, t: sv.t, owned: false, var: c}))
    subj = {name, [], nil}

    {arms, exhaustive?} =
      Enum.reduce_while(clauses, {[], MapSet.new()}, fn clause, {arms, seen} ->
        {pat, guard, body, cm} =
          case clause do
            {:->, cm, [[{:when, _, [pat, guard]}], body]} -> {pat, guard, body, cm}
            {:->, cm, [[pat], body]} -> {pat, nil, body, cm}
            {:->, cm, _} -> err!(cm, "a `case` clause takes one pattern")
          end

        {test, rename} = case_pattern(pat, sv.t, subj, cm)
        guard = guard && rename.(guard_safe!(guard, cm))
        body = rename.(body)
        seen = if guard == nil and match?({:lit, _, _}, test), do: MapSet.put(seen, elem(test, 1)), else: seen
        always? = guard == nil and (test == :any or MapSet.equal?(seen, MapSet.new([true, false])))

        cond_ast =
          cond do
            always? -> true
            test == :any -> guard
            guard == nil -> elem(test, 2)
            true -> {:and, cm, [elem(test, 2), guard]}
          end

        arms = [{cond_ast, body} | arms]
        if always?, do: {:halt, {arms, true}}, else: {:cont, {arms, seen}}
      end)

    nomatch = "defk_no_clause(ctx, #{if sv.t == :bool, do: 1, else: 0}, #{c});\n"
    # exhaustive? is the set of literals seen unless a clause always matches
    arms = Enum.reverse(arms) ++ if(exhaustive? == true, do: [], else: [{:nomatch, nomatch}])
    {[ss, "#{c} = #{sv.c};\n"], arms, env}
  end

  # {test, rename}: test is :any or {:lit | :pin, value, cond_ast}; rename
  # renames a bound variable to the subject in the guard and the body
  defp case_pattern(pat, t, subj, m) do
    same = & &1
    lit_cond = fn v -> {:===, m, [subj, v]} end

    case {pat, t} do
      {n, :i64} when is_integer(n) ->
        {{:lit, n, lit_cond.(n)}, same}

      {{:-, _, [n]}, :i64} when is_integer(n) ->
        {{:lit, -n, lit_cond.(-n)}, same}

      {b, :bool} when is_boolean(b) ->
        {{:lit, b, lit_cond.(b)}, same}

      {{:^, _, [{v, _, ctx} = var]}, _} when is_atom(v) and is_atom(ctx) ->
        {{:pin, v, {:===, m, [subj, var]}}, same}

      {{v, _, ctx}, _} when is_atom(v) and is_atom(ctx) ->
        if String.starts_with?(Atom.to_string(v), "_"),
          do: {:any, same},
          else: {:any, &rename_var(&1, v, subj)}

      {p, _} when is_integer(p) or is_boolean(p) ->
        err!(m, "`case` pattern #{inspect(p)} can never match a #{fmt(t)} subject")

      {p, _} ->
        err!(m, "unsupported `case` pattern #{Macro.to_string(p)}; use an integer literal, true/false, ^var, _ or a variable, with an optional guard")
    end
  end

  # every occurrence of variable `name` in `ast` (a consistent renaming, so
  # rebinding and shadowing inside keep their meaning)
  defp rename_var(ast, name, {to, _, _}) do
    Macro.prewalk(ast, fn
      {^name, meta, ctx} when is_atom(ctx) -> {to, meta, nil}
      other -> other
    end)
  end

  # Elixir allows only guard-safe expressions in guards: no kernel calls,
  # indexing or `&&`. An error in a defk guard (overflow, rem by zero) raises,
  # where Elixir would fail the clause.
  @guard_ops [:+, :-, :*, :/, :==, :!=, :===, :!==, :<, :>, :<=, :>=, :and, :or, :not,
              :div, :rem, :abs, :trunc, :round, :min, :max]

  defp guard_safe!(guard, m) do
    case guard do
      x when is_number(x) or is_boolean(x) -> :ok
      {v, _, ctx} when is_atom(v) and is_atom(ctx) -> :ok
      {op, _, args} when op in @guard_ops and is_list(args) -> Enum.each(args, &guard_safe!(&1, m))
      other -> err!(Keyword.put_new(meta(other), :line, m[:line]), "#{Macro.to_string(other)} is not allowed in a `case` guard; guards may use variables, literals, arithmetic, comparisons, and/or/not, div, rem, abs, trunc, round, min and max")
    end

    guard
  end

  # `weight` back-edges are charged to the budget at once
  defp safepoint(weight \\ "1") do
    n = Process.get(:defk_sp) + 1
    Process.put(:defk_sp, n)
    Process.put(:defk_sps, [{n, Enum.reverse(Process.get(:defk_loops))} | Process.get(:defk_sps)])
    "DEFK_SP(#{n}, #{weight})\n"
  end

  # ---------------------------------------------------------- range facts --
  # An i64 value may carry facts that let a[i] skip its bounds check:
  #   lo, hi - constants with lo <= v <= hi (nil = unknown)
  #   lb, ub - %{array_cvar => k}: v >= len(array) + k, v <= len(array) + k
  # An array may carry len_lo / len_lb: the same lower bounds for its length.
  # Facts are exact for checked arithmetic (an overflow raises, never wraps).
  # They name array C variables, which are assigned in one place, never change
  # length, and stay in scope only where every fact about them was derived.

  defp lb(v), do: v[:lb] || %{}
  defp ub(v), do: v[:ub] || %{}
  defp len_lb(a), do: a[:len_lb] || %{}

  defp u8_val(c), do: Map.merge(val(c, :i64), %{lo: 0, hi: 255})

  # 0 <= i < len(a)
  defp in_bounds?(a, i) do
    below? =
      Map.get(ub(i), a.c, 0) < 0 or
        (is_integer(a[:len_lo]) and is_integer(i[:hi]) and i[:hi] < a[:len_lo]) or
        Enum.any?(len_lb(a), fn {y, d} -> match?(%{^y => o} when o - d < 0, ub(i)) end)

    is_integer(i[:lo]) and i[:lo] >= 0 and below?
  end

  defp add_facts(a, b) do
    %{
      lo: add(a[:lo], b[:lo]),
      hi: add(a[:hi], b[:hi]),
      lb: Map.merge(shift(lb(a), b[:lo]), shift(lb(b), a[:lo]), fn _, x, y -> max(x, y) end),
      ub: Map.merge(shift(ub(a), b[:hi]), shift(ub(b), a[:hi]), fn _, x, y -> min(x, y) end)
    }
  end

  defp sub_facts(a, b) do
    %{
      lo: add(a[:lo], neg(b[:hi])),
      hi: add(a[:hi], neg(b[:lo])),
      lb: shift(lb(a), neg(b[:hi])),
      ub: shift(ub(a), neg(b[:lo]))
    }
  end

  defp minmax_facts(:min, a, b) do
    %{
      lo: both(a[:lo], b[:lo], &min/2),
      hi: either(a[:hi], b[:hi], &min/2),
      lb: Map.intersect(lb(a), lb(b), fn _, x, y -> min(x, y) end),
      ub: Map.merge(ub(a), ub(b), fn _, x, y -> min(x, y) end)
    }
  end

  defp minmax_facts(:max, a, b) do
    %{
      lo: either(a[:lo], b[:lo], &max/2),
      hi: both(a[:hi], b[:hi], &max/2),
      lb: Map.merge(lb(a), lb(b), fn _, x, y -> max(x, y) end),
      ub: Map.intersect(ub(a), ub(b), fn _, x, y -> max(x, y) end)
    }
  end

  defp add(x, y), do: both(x, y, &+/2)

  defp neg(x) when is_integer(x), do: -x
  defp neg(_), do: nil

  defp shift(_facts, nil), do: %{}
  defp shift(facts, k), do: Map.new(facts, fn {arr, o} -> {arr, o + k} end)

  # combine optional bounds: `both` needs both known, `either` is valid with one
  defp both(x, y, f) when is_integer(x) and is_integer(y), do: f.(x, y)
  defp both(_, _, _), do: nil

  defp either(nil, y, _), do: y
  defp either(x, nil, _), do: x
  defp either(x, y, f), do: f.(x, y)

  defp literal_int(n) when is_integer(n), do: n
  defp literal_int({:-, _, [n]}) when is_integer(n), do: -n
  defp literal_int(_), do: nil

  # ------------------------------------------------------------ emitting ---

  defp emit_entry(k) do
    f = "frame_#{k.cid}"
    arrays = for {{p, {:arr, _}}, i} <- Enum.with_index(k.params), do: {p, i}
    scalars = for {{p, t}, i} <- Enum.with_index(k.params), t in @scalars, do: {p, t, i}
    saved = Enum.map(scalars, fn {p, _, _} -> "p_#{sanitize(p)}" end) ++ Enum.map(k.decls, &elem(&1, 0))
    yields? = k.yield and k.sp_count > 0

    fields =
      Enum.map(k.params, fn {p, t} -> "  #{ctype(t)} p_#{sanitize(p)};\n" end) ++
        Enum.map(k.decls, fn {c, ct} -> "  #{ct} #{c};\n" end)

    bind =
      Enum.map(arrays, fn {p, i} ->
        {:arr, e} = Keyword.fetch!(k.params, p)
        sp = "p_#{sanitize(p)}"

        # bind through temporaries: if the view's address escaped, clang would
        # reload data/len on every iteration (the yield call might change them)
        "{ void *d; int64_t l; defk_bind(env, ctx, argv[#{i}], sizeof(*#{sp}.data), &d, &l, &F->copy[#{i}], #{i + 1}, \"#{p}\", \"#{e}\"); #{sp}.data = d; #{sp}.len = l; }\n"
      end)

    decode =
      Enum.map(scalars, fn {p, t, i} ->
        "p_#{sanitize(p)} = defk_get_#{t}_arg(env, ctx, argv[#{i}], #{i + 1}, \"#{p}\");\n"
      end)

    result =
      case k.ret_vals do
        [{c, t}] -> to_term(c, t)
        many -> "enif_make_tuple(env, #{length(many)}#{Enum.map(many, fn {c, t} -> ", " <> to_term(c, t) end)})"
      end

    sp_macro =
      if yields? do
        "#define DEFK_SP(N, W) if (DEFK_UNLIKELY((defk_ticks += (W)) >= defk_budget)) { defk_ticks = 0; if (!(defk_budget = defk_tick(env, &defk_clk, defk_budget))) { if (DEFK_UNLIKELY(F->resume)) { defk_lost_resume(ctx, F->resume, N); return DEFK_ERR; } #{Enum.map(saved, &"F->#{&1} = #{&1}; ")}F->resume = N; F->budget = defk_clk.budget; return DEFK_YIELD; } }\n" <>
          "#define DEFK_SHORT(R) DEFK_LIKELY((R) < DEFK_STRIP)\n#define DEFK_TICKS(W) defk_ticks += (W);\n#define DEFK_RESUMING DEFK_UNLIKELY(defk_rs)\n"
      else
        @no_yield_macros
      end

    [
      "/* ---- #{k.name}/#{k.arity}#{if yields?, do: " (yielding)", else: ""} ---- */\n",
      "typedef struct {\n  defk_ctx ctx;\n  int resume;\n  int64_t budget;\n  int copy[#{max(k.arity, 1)}];\n",
      fields,
      "} #{f};\n\n",
      # noinline: keep the kernel body out of the setjmp frame below
      "static __attribute__((noinline)) int run_#{k.cid}(ErlNifEnv *env, #{f} *F, const ERL_NIF_TERM *argv, ERL_NIF_TERM *result) {\n",
      "defk_ctx *ctx = &F->ctx;\n",
      if(yields?, do: "int defk_rs = F->resume;\nint64_t defk_ticks = 0;\nint64_t defk_budget = defk_rs ? F->budget : DEFK_BUDGET0;\ndefk_clock defk_clk;\ndefk_clock_init(&defk_clk);\n", else: ""),
      Enum.map(k.params, fn {p, t} -> "#{ctype(t)} p_#{sanitize(p)} = {0};\n" end),
      decl_locals(k),
      bind,
      if yields? do
        ["if (defk_rs) {\n", Enum.map(saved, &"#{&1} = F->#{&1};\n"),
         "switch (defk_rs) {\n", resume_cases(k.sps, []), "}\n}\n"]
      else
        ""
      end,
      decode,
      sp_macro,
      k.stmts,
      "*result = #{result};\nreturn DEFK_DONE;\n", @undef_macros, "}\n\n",
      # setjmp lives in a separate frame so it does not pessimise the kernel body
      "static __attribute__((noinline)) int guard_#{k.cid}(ErlNifEnv *env, #{f} *F, const ERL_NIF_TERM *argv, ERL_NIF_TERM *result) {\n",
      "if (sigsetjmp(F->ctx.jb, 0)) return DEFK_ERR;\nreturn run_#{k.cid}(env, F, argv, result);\n}\n\n",
      if yields? do
        ["static ERL_NIF_TERM step_#{k.cid}(ErlNifEnv *env, int argc, const ERL_NIF_TERM argv[]) {\n",
         "#{f} *F;\nERL_NIF_TERM res;\n",
         "enif_get_resource(env, argv[0], defk_frame_rt, (void **)&F);\n",
         "int r = guard_#{k.cid}(env, F, argv + 1, &res);\n",
         "if (DEFK_UNLIKELY(r == DEFK_DONE && F->resume)) { defk_lost_resume(&F->ctx, F->resume, 0); r = DEFK_ERR; }\n",
         "if (r == DEFK_YIELD) {\natomic_fetch_add(&defk_stat_yields, 1);\n",
         "return enif_schedule_nif(env, \"#{k.name}\", 0, step_#{k.cid}, argc, argv);\n}\n",
         "defk_finish(&F->ctx);\n",
         "return r == DEFK_ERR ? defk_raise(env, &F->ctx) : res;\n}\n\n"]
      else
        ""
      end,
      "static ERL_NIF_TERM nif_#{k.cid}(ErlNifEnv *env, int argc, const ERL_NIF_TERM argv[]) {\n",
      "#{f} local;\nERL_NIF_TERM res;\n",
      "local.ctx.err = 0;\nlocal.ctx.owned = NULL;\nlocal.ctx.nowned = local.ctx.cap = 0;\nlocal.ctx.finished = local.ctx.is_resource = 0;\n",
      "local.resume = 0;\nmemset(local.copy, 0, sizeof local.copy);\n",
      "int r = guard_#{k.cid}(env, &local, argv, &res);\n",
      if yields? do
        ["if (r == DEFK_YIELD) {\n",
         "ERL_NIF_TERM args2[#{k.arity + 1}];\n",
         "defk_promote(env, &local, sizeof local, &args2[0]);\n",
         "memcpy(args2 + 1, argv, sizeof(ERL_NIF_TERM) * argc);\n",
         "atomic_fetch_add(&defk_stat_yields, 1);\n",
         "return enif_schedule_nif(env, \"#{k.name}\", 0, step_#{k.cid}, argc + 1, args2);\n}\n"]
      else
        ""
      end,
      "defk_finish(&local.ctx);\n",
      "return r == DEFK_ERR ? defk_raise(env, &local.ctx) : res;\n}\n\n"
    ]
  end

  defp emit_init(module, kernels, nif_name) do
    funcs =
      Enum.map(kernels, fn k -> "  {\"#{nif_name.(k.name)}\", #{k.arity}, nif_#{k.cid}, 0},\n" end)

    [
      "static ErlNifFunc defk_funcs[] = {\n",
      funcs,
      "  {\"__defk_stats__\", 0, defk_stats_nif, 0},\n",
      "  {\"__defk_force_yields__\", 1, defk_force_yields_nif, 0},\n};\n\n",
      "ERL_NIF_INIT(#{Atom.to_string(module)}, defk_funcs, defk_load, NULL, defk_upgrade, NULL)\n"
    ]
  end

  defp decl_locals(k), do: Enum.map(k.decls, fn {c, ct} -> "#{ct} #{c} = {0};\n" end)

  defp to_term(c, :i64), do: "enif_make_int64(env, #{c})"
  defp to_term(c, :f64), do: "defk_make_f64(ctx, env, #{c})"
  defp to_term(c, :bool), do: "defk_make_bool(env, #{c})"
  defp to_term(c, {:arr, _}), do: "defk_make_arr(env, ctx, (#{c}).data)"

  # -------------------------------------------------------------- helpers --

  defp val(c, t, var \\ nil), do: %{c: c, t: t, owned: false, var: var}

  defp fresh(base, t) do
    n = Process.get(:defk_n) + 1
    Process.put(:defk_n, n)
    c = "v_#{sanitize(base)}_#{n}"
    Process.put(:defk_decls, [{c, ctype(t)} | Process.get(:defk_decls)])
    c
  end

  defp ctype(:i64), do: "int64_t"
  defp ctype(:f64), do: "double"
  defp ctype(:bool), do: "int"
  defp ctype({:arr, e}), do: "defk_arr_#{e}"
  defp ctype({:c, ct}), do: ct

  defp to_f(%{t: :i64, c: c}), do: "((double)#{c})"
  defp to_f(%{c: c}), do: c

  defp numeric?(v), do: v.t in [:i64, :f64]
  defp numeric!(v, m, op), do: numeric?(v) || err!(m, "#{op} expects numbers, got #{fmt(v.t)}")
  defp bool!(v, m, op), do: v.t == :bool || err!(m, "#{op} expects a boolean, got #{fmt(v.t)}")

  defp cop(:===), do: "=="
  defp cop(:!==), do: "!="
  defp cop(op), do: Atom.to_string(op)

  defp fmt({:arr, e}), do: "[#{e}]"
  defp fmt({:tuple, ts}), do: "{#{Enum.map_join(ts, ", ", &fmt/1)}}"
  defp fmt(t), do: Atom.to_string(t)

  defp sanitize(name), do: name |> to_string() |> String.replace(~r/[^A-Za-z0-9_]/, "_")

  defp meta({_, m, _}) when is_list(m), do: m
  defp meta(_), do: []

  defp err!(meta, msg) do
    raise CompileError, file: Process.get(:defk_file), line: meta[:line] || 0, description: "defk: " <> msg
  end
