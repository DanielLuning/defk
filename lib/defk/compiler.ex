  # copying input array `arr` into a writable array from alloc/2
  defp copy_rewrite(arr, {:arr, e}) do
    a = Macro.to_string(arr)

    "#{a}_copy = alloc(#{e}, len(#{a}))\n\nfor i <- 0..(len(#{a}) - 1)//1 do\n  #{a}_copy[i] = #{a}[i]\nend\n"
  end

